test("commitment generation", async (t) => {
  await t.test("values are inside the BN254 scalar field", () => {
    for (let i = 0; i < 20; i++) {
      assert.ok(randomFieldElement() < FIELD_PRIME);
    }
  });

  await t.test("a commitment is self-consistent", () => {
    const identity = generateCommitment();
    const derived = deriveFromSecrets(identity.nullifier, identity.secret);
    assert.equal(derived.commitment, identity.commitment);
    assert.equal(derived.nullifierHash, identity.nullifierHash);
  });

  await t.test("two commitments differ", () => {
    const a = generateCommitment();
    const b = generateCommitment();
    assert.notEqual(a.commitment, b.commitment);
    assert.notEqual(a.nullifierHash, b.nullifierHash);
  });

  await t.test("every field is a decimal string, never a bigint", () => {
    const identity = generateCommitment();
    for (const value of Object.values(identity)) {
      assert.equal(typeof value, "string");
      assert.match(value, /^\d+$/);
    }
  });
});

