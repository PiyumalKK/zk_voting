test("against the circuit's own fixture", async (t) => {
  await t.test("deriveFromSecrets reproduces the fixture's nullifier hash", () => {
    const { nullifierHash } = deriveFromSecrets(FIXTURE.nullifier, FIXTURE.secret);
    assert.equal(nullifierHash, FIXTURE.nullifierHash);
  });

  await t.test("findCircuitIndex recovers the fixture's index from its root", () => {
    const { commitment } = deriveFromSecrets(FIXTURE.nullifier, FIXTURE.secret);
    const found = findCircuitIndex(commitment, FIXTURE.siblings, FIXTURE.root);
    assert.equal(found, FIXTURE.index);
  });

  await t.test("a wrong root yields no index rather than a plausible one", () => {
    const { commitment } = deriveFromSecrets(FIXTURE.nullifier, FIXTURE.secret);
    const wrongRoot = (BigInt(FIXTURE.root) + 1n).toString();
    assert.equal(findCircuitIndex(commitment, FIXTURE.siblings, wrongRoot), -1);
  });
});

test("against the compiled circuit's ABI", async (t) => {
  const circuit = JSON.parse(readFileSync(CIRCUITS_JSON, "utf8"));
  const params = circuit.abi.parameters;

  await t.test("buildCircuitInputs supplies exactly the declared parameters", () => {
    const inputs = buildCircuitInputs({
      nullifier: FIXTURE.nullifier,
      secret: FIXTURE.secret,
      circuitIndex: FIXTURE.index,
      siblings: FIXTURE.siblings,
      root: FIXTURE.root,
      candidateIndex: 1,
      depth: FIXTURE.depth,
    });
    assert.deepEqual(Object.keys(inputs).sort(), params.map((p) => p.name).sort());
  });

  await t.test("the sibling array length matches the circuit's declaration", () => {
    const siblingsParam = params.find((p) => p.name === "siblings");
    assert.equal(siblingsParam.type.length, CIRCUIT_DEPTH);
  });

  await t.test("every value is a string or an array of strings, as Noir's ABI expects", () => {
    const inputs = buildCircuitInputs({
      nullifier: FIXTURE.nullifier,
      secret: FIXTURE.secret,
      circuitIndex: FIXTURE.index,
      siblings: FIXTURE.siblings,
      root: FIXTURE.root,
      candidateIndex: 1,
      depth: FIXTURE.depth,
    });
    for (const [key, value] of Object.entries(inputs)) {
      if (Array.isArray(value)) {
        assert.equal(value.length, CIRCUIT_DEPTH, `${key} length`);
        for (const item of value) assert.equal(typeof item, "string", `${key} item type`);
      } else {
        assert.equal(typeof value, "string", `${key} type`);
        assert.match(value, /^\d+$/, `${key} should be a decimal string`);
      }
    }
  });
});

