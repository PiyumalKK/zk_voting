test("buildMerklePath", async (t) => {
  /** Synthesise the NewLeaf events a division would have emitted for `leaves`. */
  const eventsFor = (leaves) => leaves.map((value, index) => ({ index, value }));

  /**
   * Walk the path the way the CIRCUIT does — little-endian index bits, poseidon2
   * at each level, over the first `depth` siblings — rather than the way LeanIMT
   * does. That is the whole point of the circuit index, so verifying it any
   * other way would verify nothing.
   */
  const circuitRoot = (leaf, siblings, index, depth) => {
    let current = BigInt(leaf);
    for (let level = 0; level < depth; level++) {
      const sibling = BigInt(siblings[level]);
      const isRight = (index >> level) & 1;
      current = isRight ? poseidon2([sibling, current]) : poseidon2([current, sibling]);
    }
    return current;
  };

  for (const size of [1, 2, 3, 5, 8, 9]) {
    await t.test(`a ${size}-leaf tree produces a path the circuit would accept`, () => {
      const identities = Array.from({ length: size }, () => generateCommitment());
      const leaves = identities.map((i) => BigInt(i.commitment));
      const target = identities[Math.floor(size / 2)];

      const path = buildMerklePath({
        leafEvents: eventsFor(leaves),
        treeSize: size,
        commitment: target.commitment,
      });

      assert.equal(path.treeSize, size);
      assert.equal(path.siblings.length, CIRCUIT_DEPTH, "always padded to the circuit's fixed width");
      // depth 0 is legal and reachable: a division with exactly one registered
      // voter has a tree whose root IS the commitment, so the path has no
      // siblings at all. The circuit accepts that (it counts non-zero siblings
      // itself) and Voting.vote()'s only root precondition is that it is
      // non-zero, which a commitment always is.
      assert.ok(path.depth >= 0 && path.depth <= CIRCUIT_DEPTH, `depth ${path.depth} out of range`);
      assert.equal(path.depth === 0, size === 1, "only a single-voter division has an empty path");
      assert.ok(
        path.siblings.slice(path.depth).every((s) => s === "0"),
        "everything past `depth` must be padding",
      );
      assert.equal(BigInt(path.root), rebuildTree(leaves).root, "the root is LeanIMT's own");
      assert.equal(
        circuitRoot(target.commitment, path.siblings, path.circuitIndex, path.depth),
        BigInt(path.root),
        "the circuit's own walk reproduces that root",
      );
    });
  }

  await t.test("an unknown commitment is reported, not silently proved", () => {
    const leaves = [1n, 2n, 3n];
    assert.throws(
      () => buildMerklePath({ leafEvents: eventsFor(leaves), treeSize: 3, commitment: 99n }),
      /commitment not found/,
    );
  });

  await t.test("an empty tree is reported", () => {
    assert.throws(() => buildMerklePath({ leafEvents: [], treeSize: 0, commitment: 1n }), /no voters registered/);
  });

  await t.test("the leaf index is the position in the current election's tree", () => {
    const leaves = [10n, 20n, 30n, 40n];
    const path = buildMerklePath({ leafEvents: eventsFor(leaves), treeSize: 4, commitment: 30n });
    assert.equal(path.leafIndex, 2);
  });
});

