test("leavesFromEvents", async (t) => {
  const event = (index, value) => ({ index, value: BigInt(value) });

  await t.test("orders by the emitted index, not by log order", () => {
    const leaves = leavesFromEvents([event(1, 20), event(0, 10), event(2, 30)], 3);
    assert.deepEqual(leaves, [10n, 20n, 30n]);
  });

  await t.test("keeps only the current election's leaves after a reset", () => {
    // Two elections' worth of logs; resetElection() left the tree at size 2.
    const logs = [event(0, 111), event(1, 222), event(2, 333), event(0, 44), event(1, 55)];
    assert.deepEqual(leavesFromEvents(logs, 2), [44n, 55n]);
  });

  await t.test("accepts bigint indices, as viem decodes uint256", () => {
    assert.deepEqual(leavesFromEvents([event(1n, 20), event(0n, 10)], 2), [10n, 20n]);
  });

  await t.test("refuses to return a short list", () => {
    assert.throws(() => leavesFromEvents([event(0, 10)], 3), /does not match on-chain tree size/);
  });

  await t.test("an empty current election returns no leaves, not every leaf", () => {
    // Regression: `slice(-0)` is `slice(0)`, so a size-0 tree with historic
    // logs would otherwise return the whole history.
    assert.deepEqual(leavesFromEvents([event(0, 111), event(1, 222)], 0), []);
    assert.deepEqual(leavesFromEvents([], 0), []);
  });

  await t.test("rejects a nonsensical tree size", () => {
    assert.throws(() => leavesFromEvents([], -1), /non-negative integer/);
    assert.throws(() => leavesFromEvents([], 1.5), /non-negative integer/);
  });
});

