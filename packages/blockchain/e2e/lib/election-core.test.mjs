test("toBytes32", async (t) => {
  await t.test("zero is 32 zero bytes, not '0x0'", () => {
    assert.equal(toBytes32("0"), `0x${"0".repeat(64)}`);
  });

  await t.test("a small value is left-padded", () => {
    assert.equal(toBytes32(1), `0x${"0".repeat(63)}1`);
  });

  await t.test("accepts decimal strings, hex strings and bigints alike", () => {
    assert.equal(toBytes32("255"), toBytes32("0xff"));
    assert.equal(toBytes32(255n), toBytes32("0xff"));
  });

  await t.test("a full-width field element keeps all 64 nibbles", () => {
    const encoded = toBytes32(FIELD_PRIME - 1n);
    assert.equal(encoded.length, 66);
    assert.equal(BigInt(encoded), FIELD_PRIME - 1n);
  });

  await t.test("refuses values that do not fit, rather than truncating", () => {
    assert.throws(() => toBytes32(2n ** 256n), /does not fit in 32 bytes/);
    assert.throws(() => toBytes32(-1n), /negative/);
  });
});

