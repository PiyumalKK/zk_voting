test("padSiblings", async (t) => {
  await t.test("pads to the circuit's fixed length with zeros", () => {
    const padded = padSiblings(["1", "2"]);
    assert.equal(padded.length, CIRCUIT_DEPTH);
    assert.deepEqual(padded.slice(0, 2), ["1", "2"]);
    assert.ok(padded.slice(2).every((s) => s === "0"));
  });

  await t.test("normalises bigints and hex to decimal strings", () => {
    assert.deepEqual(padSiblings([255n, "0xff"]).slice(0, 2), ["255", "255"]);
  });

  await t.test("refuses a path longer than the circuit accepts", () => {
    assert.throws(() => padSiblings(Array(17).fill("1")), /exceeds the circuit's 16/);
  });

  await t.test("leaves an already-full path alone", () => {
    const full = Array.from({ length: CIRCUIT_DEPTH }, (_, i) => String(i + 1));
    assert.deepEqual(padSiblings(full), full);
  });
});

