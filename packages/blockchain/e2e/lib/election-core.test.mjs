// Offline unit tests for ./election-core.mjs.
//
//   node --test lib/election-core.test.mjs
//   (or, from packages/blockchain: `make e2e-core-test`)
//
// No node, no chain, no network, no proving — seconds, not minutes. The full
// election harness is expensive and needs a Go toolchain; the logic most
// likely to be subtly wrong needs neither, so it is tested here.
//
// Two of these suites are worth more than the rest, because they check against
// something OUTSIDE this repo's JavaScript:
//
//   - "against the circuit's own fixture" uses packages/circuits/Prover.toml,
//     whose values were produced independently and verified by `nargo`. If
//     poseidon-lite, the field, or the path-walking bit order ever diverged
//     from what the circuit computes, that suite fails. Testing poseidon
//     against poseidon would not.
//   - "against the compiled circuit's ABI" reads the real circuits.json and
//     asserts our witness object has exactly the parameters the circuit
//     declares, with the declared array length. A renamed or reordered input
//     is caught here rather than as an opaque bb.js failure ten minutes into
//     the gate.

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

import { poseidon2 } from "poseidon-lite";

import {
  CIRCUIT_DEPTH,
  FIELD_PRIME,
  buildCircuitInputs,
  buildMerklePath,
  buildVoteArgs,
  deriveFromSecrets,
  findCircuitIndex,
  generateCommitment,
  leavesFromEvents,
  padSiblings,
  randomFieldElement,
  rebuildTree,
  toBytes32,
} from "./election-core.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const CIRCUITS_JSON = join(here, "..", "..", "..", "nextjs", "public", "circuits.json");

// packages/circuits/Prover.toml, verbatim. Generated by
// packages/nextjs/generate_prover_inputs.mjs and accepted by the circuit, so
// these are known-good values from outside this file's own arithmetic.
const FIXTURE = {
  nullifier: "42",
  secret: "123",
  nullifierHash: "12326503012965816391338144612242952408728683609716147019497703475006801258307",
  root: "14323779011469951618447924429445439226819608782236079685175267553238899867272",
  siblings: ["111", "222", "333"],
  index: 2,
  depth: 3,
};

