test("buildVoteArgs", async (t) => {
  const inputs = buildCircuitInputs({
    nullifier: FIXTURE.nullifier,
    secret: FIXTURE.secret,
    circuitIndex: FIXTURE.index,
    siblings: FIXTURE.siblings,
    root: FIXTURE.root,
    candidateIndex: 1,
    depth: FIXTURE.depth,
  });

  await t.test("produces the five arguments Voting.vote() takes", () => {
    const args = buildVoteArgs(inputs, "0xdeadbeef");
    assert.deepEqual(Object.keys(args), ["proof", "nullifierHash", "root", "vote", "depth"]);
    for (const key of ["nullifierHash", "root", "vote", "depth"]) {
      assert.equal(args[key].length, 66, `${key} should be a 32-byte word`);
    }
  });

  await t.test("the encoded words round-trip to the circuit's public inputs", () => {
    const args = buildVoteArgs(inputs, "0x00");
    assert.equal(BigInt(args.nullifierHash).toString(), inputs.nullifier_hash);
    assert.equal(BigInt(args.root).toString(), inputs.root);
    assert.equal(BigInt(args.vote).toString(), inputs.vote);
    assert.equal(BigInt(args.depth).toString(), inputs.depth);
  });

  await t.test("rejects a proof that is not hex", () => {
    assert.throws(() => buildVoteArgs(inputs, "deadbeef"), /0x-prefixed hex/);
    assert.throws(() => buildVoteArgs(inputs, "0xzz"), /0x-prefixed hex/);
    assert.throws(() => buildVoteArgs(inputs, undefined), /0x-prefixed hex/);
  });
});
